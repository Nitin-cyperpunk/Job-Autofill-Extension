import type { FieldKey, FieldType } from '@jobfill/types';

/**
 * The deterministic mapping dictionary: which words on a form mean which profile
 * value. Phrases are written naturally here and normalized at load time with the
 * same normalizeText() used on page text ("E-mail" and "email" are the same).
 *
 * Adding coverage = adding phrases. Keep excludes for the classic false friends
 * ("Email address" is not an address; "Reference phone" is not your phone).
 */

export type SectionContext = 'education' | 'experience';

export interface MappingRule {
  key: FieldKey;
  phrases: string[];
  /** If any of these phrases appear, the rule doesn't apply. */
  exclude?: string[];
  /** Only applies inside an Education / Experience section. */
  context?: SectionContext;
  /** Doesn't apply inside an Education / Experience section (e.g. top-level "City"). */
  avoidContext?: boolean;
  /** Field types the rule may map. Defaults to TEXTUAL. */
  types?: readonly FieldType[];
}

